namespace Viktor.Localization;

/// <summary>
/// Every user-facing string, keyed by area. XAML binds to the indexer
/// (<c>{Binding [Main.Save], Source={x:Static loc:Strings.Current}}</c>) so switching
/// the language refreshes whatever is already on screen.
/// </summary>
public sealed class Strings : INotifyPropertyChanged
{
    private static readonly Strings Instance = new();

    private Language _language = LocalSettings.Load();

    public static Strings Current => Instance;

    public event PropertyChangedEventHandler? PropertyChanged;

    /// <summary>Raised after the language changes, for text set from code.</summary>
    public event Action? LanguageChanged;

    public Language Language
    {
        get => _language;
        set
        {
            if (_language == value)
            {
                return;
            }

            _language = value;
            LocalSettings.Store(value);

            // An empty name means "everything on this source changed", which refreshes
            // every indexer binding in one go.
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(string.Empty));
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
            LanguageChanged?.Invoke();
        }
    }

    /// <summary>Text for a key in the current language.</summary>
    public string this[string key] => Get(key);

    /// <summary>
    /// Text for a key. Falls back to <paramref name="fallback"/> when the key is not
    /// translated, which is how the action catalogue keeps its English text inline.
    /// </summary>
    public static string Get(string key, string? fallback = null)
    {
        // Chrome text lives in this file, action text in ActionStrings; both are Chinese only.
        if (Instance._language == Language.Chinese
            && (Chinese.TryGetValue(key, out var chinese)
                || ActionStrings.Chinese.TryGetValue(key, out chinese)))
        {
            return chinese;
        }

        if (English.TryGetValue(key, out var english))
        {
            return english;
        }

        return fallback ?? key;
    }

    /// <summary>Text for a key, with placeholders filled in by <see cref="string.Format"/>.</summary>
    public static string Format(string key, params object[] arguments)
        => string.Format(Get(key), arguments);

