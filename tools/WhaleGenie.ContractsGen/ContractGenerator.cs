using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using WhaleGenie.Contracts;

namespace WhaleGenie.ContractsGen;

/// <summary>
/// Writes the TypeScript side of the bridge contract. The page compiles against the file this
/// produces, so a field added on one side and forgotten on the other is a failing case rather than
/// a runtime surprise.
/// </summary>
/// <remarks>
/// The bridge serializer writes camelCase property names and writes nulls explicitly, so a
/// property that may be null becomes <c>T | null</c> in TypeScript rather than an optional field.
/// Only types marked <see cref="BridgeContractAttribute"/> are emitted; ports and helpers in the
/// same assembly stay out of the page.
/// </remarks>
public static class ContractGenerator
{
    /// <summary>The whole generated module.</summary>
    public static string Generate()
    {
        var assembly = typeof(BridgeContractAttribute).Assembly;
        var contracts = assembly.GetExportedTypes()
            .Where(type => type.GetCustomAttribute<BridgeContractAttribute>() is not null)
            .OrderBy(type => type.Name, StringComparer.Ordinal)
            .ToList();

        // A polymorphic base is written as a union of its derived records; the derived records
        // themselves are written once, with the discriminator as a literal field.
        var derivedTypes = new HashSet<Type>();
        foreach (var contract in contracts)
        {
            foreach (var option in contract.GetCustomAttributes<JsonDerivedTypeAttribute>())
            {
                if (option.DerivedType is { } derived)
                {
                    derivedTypes.Add(derived);
                }
            }
        }

        var text = new StringBuilder();
        text.AppendLine("/* Generated by tools/WhaleGenie.ContractsGen. Do not edit by hand. */");
        text.AppendLine();

        var nullability = new NullabilityInfoContext();
        foreach (var contract in contracts)
        {
            if (contract.IsInterface || contract.IsEnum)
            {
                throw new NotSupportedException(
                    $"{contract} is marked as a bridge contract but is not a record");
            }

            if (derivedTypes.Contains(contract))
            {
                // Emitted with the base's union, after the union alias.
                continue;
            }

            if (contract.GetCustomAttribute<JsonPolymorphicAttribute>() is { } polymorphic)
            {
                var options = contract.GetCustomAttributes<JsonDerivedTypeAttribute>().ToList();
                var discriminator = polymorphic.TypeDiscriminatorPropertyName ?? "$type";
                text.Append("export type ").Append(contract.Name).AppendLine(" =");
                for (var index = 0; index < options.Count; index++)
                {
                    text.Append("  | ").Append(options[index].DerivedType!.Name)
                        .AppendLine(index == options.Count - 1 ? ";" : string.Empty);
                }

                text.AppendLine();
                foreach (var option in options)
                {
                    // A command is a request: an optional field may be left out, while the
                    // required ones and the discriminator stay required.
                    WriteInterface(text, option.DerivedType!, nullability, patch: false,
                        discriminator, option.TypeDiscriminator, optionalNullables: true);
                }

                continue;
            }

            // A patch's absent field means "leave it alone"; every property is optional. Other
            // records are whole snapshots, so a nullable property is present and explicitly null.
            WriteInterface(text, contract, nullability,
                contract.GetCustomAttribute<BridgePatchAttribute>() is not null,
                discriminator: null, discriminatorValue: null, optionalNullables: false);
        }

        // Line endings are part of the generated artifact: the same contract must produce the
        // same bytes on every machine, and the web build does not care which one wrote it.
        return text.ToString().Replace("\r\n", "\n", StringComparison.Ordinal).TrimEnd() + "\n";
    }

    private static void WriteInterface(StringBuilder text, Type contract,
        NullabilityInfoContext nullability, bool patch, string? discriminator,
        object? discriminatorValue, bool optionalNullables)
    {
        text.Append("export interface ").Append(contract.Name).AppendLine(" {");
        if (discriminator is not null)
        {
            text.Append("  ").Append(JsonNamingPolicy.CamelCase.ConvertName(discriminator))
                .Append(": '").Append(discriminatorValue).AppendLine("';");
        }

        var properties = contract.GetProperties(BindingFlags.Public | BindingFlags.Instance)
            .OrderBy(property => property.MetadataToken);
        foreach (var property in properties)
        {
            var info = nullability.Create(property);
            var nullable = Nullable.GetUnderlyingType(property.PropertyType) is not null
                           || info.ReadState == NullabilityState.Nullable;
            text.Append("  ")
                .Append(JsonNamingPolicy.CamelCase.ConvertName(property.Name))
                .Append(patch || (optionalNullables && nullable) ? "?: " : ": ")
                .Append(TypeScript(property.PropertyType))
                .Append(nullable ? " | null" : string.Empty)
                .AppendLine(";");
        }

        text.AppendLine("}");
        text.AppendLine();
    }

    /// <summary>The page's union of callable method names.</summary>
    public static string GenerateMethods()
    {
        var text = new StringBuilder();
        text.AppendLine("/* Generated by tools/WhaleGenie.ContractsGen. Do not edit by hand. */");
        text.AppendLine();
        text.AppendLine("export type BridgeMethod =");
        text.AppendLine("  | 'bridge.ready' // client handshake, not a registered method");
        foreach (var name in BridgeMethods.All.Order(StringComparer.Ordinal))
        {
            text.Append("  | '").Append(name).AppendLine("'");
        }

        return text.ToString().Replace("\r\n", "\n", StringComparison.Ordinal).TrimEnd() + ";\n";
    }

    private static string TypeScript(Type type)
    {
        var underlying = Nullable.GetUnderlyingType(type) ?? type;
        if (underlying == typeof(string))
        {
            return "string";
        }

        if (underlying == typeof(bool))
        {
            return "boolean";
        }

        if (underlying == typeof(int) || underlying == typeof(long) || underlying == typeof(short)
            || underlying == typeof(byte) || underlying == typeof(double)
            || underlying == typeof(float) || underlying == typeof(decimal))
        {
            return "number";
        }

        if (underlying.IsArray)
        {
            return TypeScript(underlying.GetElementType()!) + "[]";
        }

        if (underlying.IsGenericType)
        {
            var definition = underlying.GetGenericTypeDefinition();
            var arguments = underlying.GetGenericArguments();
            if (definition == typeof(IReadOnlyList<>) || definition == typeof(List<>)
                || definition == typeof(IEnumerable<>))
            {
                return TypeScript(arguments[0]) + "[]";
            }

            if (definition == typeof(IReadOnlyDictionary<,>) || definition == typeof(Dictionary<,>))
            {
                return "{ [key: " + TypeScript(arguments[0]) + "]: " + TypeScript(arguments[1]) + " }";
            }
        }

        if (underlying.GetCustomAttribute<BridgeContractAttribute>() is not null)
        {
            return underlying.Name;
        }

        throw new NotSupportedException(
            $"the contract generator does not know how to write {underlying} as TypeScript");
    }
}
