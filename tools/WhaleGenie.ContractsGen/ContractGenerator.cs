using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using System.Text;
using System.Text.Json;
using WhaleGenie.Contracts;

namespace WhaleGenie.ContractsGen;

/// <summary>
/// Writes the TypeScript side of the bridge contract. The page compiles against the file this
/// produces, so a field added on one side and forgotten on the other is a failing case rather than
/// a runtime surprise.
/// </summary>
/// <remarks>
/// The bridge serializer writes camelCase property names and omits nulls, so the generator does
/// the same: a property that may be null becomes optional in TypeScript. Only types marked
/// <see cref="BridgeContractAttribute"/> are emitted; ports and helpers in the same assembly stay
/// out of the page.
/// </remarks>
public static class ContractGenerator
{
    /// <summary>The whole generated module.</summary>
    public static string Generate()
    {
        var assembly = typeof(BridgeContractAttribute).Assembly;
        var contracts = assembly.GetExportedTypes()
            .Where(type => type.GetCustomAttribute<BridgeContractAttribute>() is not null)
            .OrderBy(type => type.Name, StringComparer.Ordinal)
            .ToList();

        var text = new StringBuilder();
        text.AppendLine("/* Generated by tools/WhaleGenie.ContractsGen. Do not edit by hand. */");
        text.AppendLine();

        var nullability = new NullabilityInfoContext();
        foreach (var contract in contracts)
        {
            if (contract.IsInterface || contract.IsEnum)
            {
                throw new NotSupportedException(
                    $"{contract} is marked as a bridge contract but is not a record");
            }

            text.Append("export interface ").Append(contract.Name).AppendLine(" {");
            var properties = contract.GetProperties(BindingFlags.Public | BindingFlags.Instance)
                .OrderBy(property => property.MetadataToken);
            foreach (var property in properties)
            {
                var info = nullability.Create(property);
                var optional = Nullable.GetUnderlyingType(property.PropertyType) is not null
                               || info.ReadState == NullabilityState.Nullable;
                text.Append("  ")
                    .Append(JsonNamingPolicy.CamelCase.ConvertName(property.Name))
                    .Append(optional ? "?: " : ": ")
                    .Append(TypeScript(property.PropertyType))
                    .AppendLine(";");
            }

            text.AppendLine("}");
            text.AppendLine();
        }

        // Line endings are part of the generated artifact: the same contract must produce the
        // same bytes on every machine, and the web build does not care which one wrote it.
        return text.ToString().Replace("\r\n", "\n", StringComparison.Ordinal).TrimEnd() + "\n";
    }

    private static string TypeScript(Type type)
    {
        var underlying = Nullable.GetUnderlyingType(type) ?? type;
        if (underlying == typeof(string))
        {
            return "string";
        }

        if (underlying == typeof(bool))
        {
            return "boolean";
        }

        if (underlying == typeof(int) || underlying == typeof(long) || underlying == typeof(short)
            || underlying == typeof(byte) || underlying == typeof(double)
            || underlying == typeof(float) || underlying == typeof(decimal))
        {
            return "number";
        }

        if (underlying.IsArray)
        {
            return TypeScript(underlying.GetElementType()!) + "[]";
        }

        if (underlying.IsGenericType)
        {
            var definition = underlying.GetGenericTypeDefinition();
            var arguments = underlying.GetGenericArguments();
            if (definition == typeof(IReadOnlyList<>) || definition == typeof(List<>)
                || definition == typeof(IEnumerable<>))
            {
                return TypeScript(arguments[0]) + "[]";
            }

            if (definition == typeof(IReadOnlyDictionary<,>) || definition == typeof(Dictionary<,>))
            {
                return "{ [key: " + TypeScript(arguments[0]) + "]: " + TypeScript(arguments[1]) + " }";
            }
        }

        if (underlying.GetCustomAttribute<BridgeContractAttribute>() is not null)
        {
            return underlying.Name;
        }

        throw new NotSupportedException(
            $"the contract generator does not know how to write {underlying} as TypeScript");
    }
}
